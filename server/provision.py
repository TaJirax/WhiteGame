#!/usr/bin/env python3
"""Small authenticated provisioning API for an existing Linux WireGuard interface.

Client private keys are generated by the phone and are never accepted here. SQLite is
the desired-state journal; wg-quick's server configuration must not contain these peers.
Only one process may own a database. HTTP is intended for a loopback HTTPS reverse proxy.
"""
from __future__ import annotations

import base64
import hmac
import ipaddress
import json
import logging
import os
from pathlib import Path
import re
import sqlite3
import subprocess
import threading
from dataclasses import dataclass
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import unquote, urlsplit


LOG = logging.getLogger("whitegame.provision")


class ApiError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status


class DriverError(Exception):
    pass


def public_key(value: object) -> str:
    if not isinstance(value, str):
        raise ApiError(400, "public_key must be a base64 WireGuard public key")
    try:
        raw = base64.b64decode(value, validate=True)
    except (ValueError, TypeError):
        raw = b""
    if len(raw) != 32 or not any(raw) or base64.b64encode(raw).decode("ascii") != value:
        raise ApiError(400, "public_key must be a canonical 32-byte base64 WireGuard public key")
    return value


def endpoint(value: str) -> str:
    parsed = urlsplit("//" + value)
    try:
        port = parsed.port
    except ValueError as error:
        raise ValueError("WG_ENDPOINT must be host:port or [IPv6]:port") from error
    host = parsed.hostname
    if (not host or port is None or not 1 <= port <= 65535 or parsed.username is not None
            or parsed.password is not None or parsed.path or parsed.query or parsed.fragment
            or any(char.isspace() for char in value)):
        raise ValueError("WG_ENDPOINT must be host:port or [IPv6]:port")
    try:
        ipaddress.ip_address(host)
    except ValueError:
        if len(host) > 253 or not all(re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?", part)
                                      for part in host.rstrip(".").split(".")):
            raise ValueError("WG_ENDPOINT has an invalid hostname")
    return value


@dataclass(frozen=True)
class Settings:
    interface: str
    endpoint: str
    network: ipaddress.IPv4Network
    dns: tuple[str, ...]
    allowed_ips: tuple[str, ...]
    enrollment_token: str
    admin_token: str
    database: Path
    wg_bin: str = "/usr/bin/wg"
    bind_host: str = "127.0.0.1"
    bind_port: int = 8080
    mtu: int = 1280
    keepalive: int = 25

    def __post_init__(self):
        if not re.fullmatch(r"[A-Za-z0-9_.-]{1,15}", self.interface):
            raise ValueError("WG_INTERFACE must be a Linux interface name")
        endpoint(self.endpoint)
        if not isinstance(self.network, ipaddress.IPv4Network) or not 16 <= self.network.prefixlen <= 30:
            raise ValueError("WG_NETWORK must be an IPv4 subnet between /16 and /30")
        if not self.dns or any(ipaddress.ip_address(ip).version != 4 for ip in self.dns):
            raise ValueError("WG_DNS must contain IPv4 resolver addresses")
        if not self.allowed_ips or any(ipaddress.ip_network(ip).version != 4 for ip in self.allowed_ips):
            raise ValueError("WG_ALLOWED_IPS must contain IPv4 CIDRs")
        for token in (self.enrollment_token, self.admin_token):
            if len(token) < 32 or any(not 33 <= ord(char) <= 126 for char in token):
                raise ValueError("Provisioning tokens must be distinct ASCII secrets of at least 32 characters")
        if hmac.compare_digest(self.enrollment_token, self.admin_token):
            raise ValueError("Enrollment and admin tokens must differ")
        if not 576 <= self.mtu <= 9000 or not 0 <= self.keepalive <= 65535:
            raise ValueError("Invalid WG_MTU or WG_KEEPALIVE")
        if not 1 <= self.bind_port <= 65535:
            raise ValueError("Invalid WG_BIND_PORT")

    @classmethod
    def from_env(cls, env=None):
        env = os.environ if env is None else env
        def csv(name, default):
            return tuple(item.strip() for item in env.get(name, default).split(",") if item.strip())
        return cls(
            interface=env.get("WG_INTERFACE", "wg0"), endpoint=env.get("WG_ENDPOINT", ""),
            network=ipaddress.IPv4Network(env.get("WG_NETWORK", "10.8.0.0/24")),
            dns=csv("WG_DNS", "1.1.1.1,1.0.0.1"), allowed_ips=csv("WG_ALLOWED_IPS", "0.0.0.0/0"),
            enrollment_token=env.get("WG_ENROLLMENT_TOKEN", ""), admin_token=env.get("WG_ADMIN_TOKEN", ""),
            database=Path(env.get("WG_DATABASE", "/var/lib/whitegame-provision/peers.sqlite3")),
            wg_bin=env.get("WG_BIN", "/usr/bin/wg"), bind_host=env.get("WG_BIND_HOST", "127.0.0.1"),
            bind_port=int(env.get("WG_BIND_PORT", "8080")), mtu=int(env.get("WG_MTU", "1280")),
            keepalive=int(env.get("WG_KEEPALIVE", "25")))


class WireGuard:
    """Never reads private-key/PSK output, invokes a shell, or logs command output."""
    def __init__(self, settings: Settings, runner=subprocess.run):
        self.settings, self.runner = settings, runner

    def command(self, *args: str) -> str:
        try:
            result = self.runner([self.settings.wg_bin, *args], capture_output=True,
                                 text=True, timeout=8, check=False, stdin=subprocess.DEVNULL)
        except (OSError, subprocess.TimeoutExpired) as error:
            raise DriverError("WireGuard command unavailable or timed out") from error
        if result.returncode != 0:
            raise DriverError("WireGuard command failed")
        return result.stdout.strip()

    def server_key(self):
        try:
            return public_key(self.command("show", self.settings.interface, "public-key"))
        except ApiError as error:
            raise DriverError("WireGuard interface has no valid public key") from error

    def peers(self) -> dict[str, list[ipaddress.IPv4Network | ipaddress.IPv6Network]]:
        result = {}
        for line in self.command("show", self.settings.interface, "allowed-ips").splitlines():
            try:
                key, ips = line.split(maxsplit=1)
                public_key(key)
                result[key] = [] if ips == "(none)" else [ipaddress.ip_network(item, strict=False)
                                                          for item in ips.replace(",", " ").split()]
            except (ValueError, ApiError) as error:
                raise DriverError("WireGuard returned malformed peer state") from error
        return result

    def add(self, key: str, address: str):
        self.command("set", self.settings.interface, "peer", key, "allowed-ips", address)

    def remove(self, key: str):
        self.command("set", self.settings.interface, "peer", key, "remove")


class InstanceLock:
    """A lifetime OS lock prevents two reconcilers from racing between journal commits."""
    def __init__(self, path: Path):
        self.file = open(path, "a+b")
        os.chmod(path, 0o600)
        try:
            if os.name == "nt":
                import msvcrt
                self.file.write(b"\0")
                self.file.flush()
                self.file.seek(0)
                msvcrt.locking(self.file.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl
                fcntl.flock(self.file.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            self.file.close()
            raise ValueError("Another provisioner already owns this database") from error

    def close(self):
        self.file.close()


class Provisioner:
    def __init__(self, settings: Settings, driver=None):
        self.settings = settings
        self.driver = driver or WireGuard(settings)
        self.mutex = threading.RLock()
        settings.database.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.instance_lock = InstanceLock(Path(str(settings.database) + ".lock"))
        self.db = None
        try:
            descriptor = os.open(settings.database, os.O_CREAT | os.O_RDWR, 0o600)
            os.close(descriptor)
            os.chmod(settings.database, 0o600)
            self.db = sqlite3.connect(settings.database, timeout=10, check_same_thread=False)
            self.db.row_factory = sqlite3.Row
            self.db.execute("PRAGMA journal_mode=WAL")
            self.db.execute("PRAGMA synchronous=FULL")
            self.db.execute("""CREATE TABLE IF NOT EXISTS peers (
                public_key TEXT PRIMARY KEY, name TEXT NOT NULL, address TEXT NOT NULL UNIQUE,
                state TEXT NOT NULL CHECK(state IN ('pending','active','deleting')), created_at TEXT NOT NULL
            )""")
            self.db.commit()
            self.server_public_key = self.driver.server_key()
            self.db.execute("CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL)")
            identity = {"interface": settings.interface, "network": str(settings.network),
                        "server_public_key": self.server_public_key}
            with self.db:
                for key, value in identity.items():
                    previous = self.db.execute("SELECT value FROM metadata WHERE key=?", (key,)).fetchone()
                    if previous is not None and previous["value"] != value:
                        raise ValueError("Database belongs to a different WireGuard interface, key or address pool")
                    self.db.execute("INSERT OR IGNORE INTO metadata VALUES (?, ?)", (key, value))
            self.reconcile()
        except Exception:
            self.close()
            raise

    def close(self):
        if self.db is not None:
            self.db.close()
            self.db = None
        self.instance_lock.close()

    def rows(self):
        return self.db.execute("SELECT * FROM peers ORDER BY created_at, public_key").fetchall()

    def _apply(self, row, live):
        address = ipaddress.ip_network(row["address"])
        existing = live.get(row["public_key"])
        if existing is not None and existing != [address]:
            raise ApiError(409, "A managed peer was changed outside the provisioner; resolve the conflict first")
        if any(key != row["public_key"] and any(address.overlaps(network) for network in networks
                                              if network.version == 4) for key, networks in live.items()):
            raise ApiError(409, "A WireGuard peer already uses the allocated client address")
        self.driver.add(row["public_key"], row["address"])
        with self.db:
            self.db.execute("UPDATE peers SET state='active' WHERE public_key=?", (row["public_key"],))

    def reconcile(self):
        with self.mutex:
            # Revocation always wins, even if the process died just before wg remove.
            for row in self.rows():
                if row["state"] == "deleting":
                    self.driver.remove(row["public_key"])
                    with self.db:
                        self.db.execute("DELETE FROM peers WHERE public_key=?", (row["public_key"],))
            live = self.driver.peers()
            for row in self.rows():
                self._apply(row, live)
                live[row["public_key"]] = [ipaddress.ip_network(row["address"])]

    def profile(self, row):
        return dict(public_key=row["public_key"], server_public_key=self.server_public_key,
                    addresses=[row["address"]], dns=list(self.settings.dns), endpoint=self.settings.endpoint,
                    allowed_ips=list(self.settings.allowed_ips), mtu=self.settings.mtu,
                    persistent_keepalive=self.settings.keepalive)

    def check_identity(self):
        if self.driver.server_key() != self.server_public_key:
            raise DriverError("WireGuard interface key changed")

    def enroll(self, body):
        if not isinstance(body, dict) or set(body) - {"public_key", "name"}:
            raise ApiError(400, "Only public_key and optional name are accepted")
        key = public_key(body.get("public_key"))
        if key == self.server_public_key:
            raise ApiError(400, "Client and server public keys must differ")
        name = body.get("name", "WhiteGame")
        if not isinstance(name, str) or not 1 <= len(name.strip()) <= 64 or any(ord(char) < 32 for char in name):
            raise ApiError(400, "name must contain 1 to 64 printable characters")
        with self.mutex:
            self.check_identity()
            live = self.driver.peers()
            row = self.db.execute("SELECT * FROM peers WHERE public_key=?", (key,)).fetchone()
            created = row is None
            if row is not None and row["state"] == "deleting":
                raise ApiError(409, "Peer revocation is pending; ask the administrator to finish it")
            if row is None:
                if key in live:
                    raise ApiError(409, "This public key is already managed outside the provisioner")
                used = {record["address"] for record in self.rows()}
                networks = [network for values in live.values() for network in values if network.version == 4]
                # First host belongs to wg0; network and broadcast are excluded by hosts().
                hosts = iter(self.settings.network.hosts())
                next(hosts)
                address = next((f"{ip}/32" for ip in hosts if f"{ip}/32" not in used
                                and not any(ip in network for network in networks)), None)
                if address is None:
                    raise ApiError(409, "No client addresses remain in the configured pool")
                with self.db:
                    self.db.execute("INSERT INTO peers VALUES (?, ?, ?, 'pending', ?)",
                                    (key, name.strip(), address, datetime.now(timezone.utc).isoformat()))
                row = self.db.execute("SELECT * FROM peers WHERE public_key=?", (key,)).fetchone()
            self._apply(row, live)
            return self.profile(row), created

    def list_peers(self):
        with self.mutex:
            return {"peers": [dict(row) for row in self.rows()]}

    def revoke(self, key):
        key = public_key(key)
        with self.mutex:
            row = self.db.execute("SELECT * FROM peers WHERE public_key=?", (key,)).fetchone()
            if row is None:
                return  # Idempotent; never remove unmanaged peers.
            with self.db:
                self.db.execute("UPDATE peers SET state='deleting' WHERE public_key=?", (key,))
            self.driver.remove(key)
            with self.db:
                self.db.execute("DELETE FROM peers WHERE public_key=?", (key,))


def handler_for(provisioner: Provisioner):
    class Handler(BaseHTTPRequestHandler):
        server_version = "WhiteGameProvision/1"
        sys_version = ""

        def setup(self):
            super().setup()
            self.connection.settimeout(10)

        def log_message(self, *_args):
            # Request targets can contain public keys, credentials or bad terminal controls.
            pass

        def reply(self, status, body):
            raw = json.dumps(body, separators=(",", ":")).encode("utf-8")
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(raw)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Connection", "close")
            self.end_headers()
            self.wfile.write(raw)
            self.close_connection = True

        def authorized(self, admin=False):
            token = provisioner.settings.admin_token if admin else provisioner.settings.enrollment_token
            values = self.headers.get_all("Authorization", [])
            supplied = values[0] if len(values) == 1 else ""
            if not hmac.compare_digest(supplied.encode("utf-8"), ("Bearer " + token).encode("ascii")):
                raise ApiError(401, "A valid bearer token is required")

        def dispatch(self):
            try:
                if self.command == "GET" and self.path == "/healthz":
                    provisioner.check_identity()
                    self.reply(200, {"status": "ok"})
                    return
                if self.path == "/v1/peers":
                    if self.command == "POST":
                        self.authorized()
                        if self.headers.get("Transfer-Encoding"):
                            raise ApiError(400, "Chunked requests are not supported")
                        if len(self.headers.get_all("Content-Length", [])) != 1:
                            raise ApiError(411, "One Content-Length header is required")
                        try:
                            length = int(self.headers["Content-Length"])
                        except ValueError:
                            raise ApiError(400, "Invalid Content-Length")
                        if length < 1 or length > 4096:
                            raise ApiError(413, "JSON request must contain 1 to 4096 bytes")
                        if self.headers.get_content_type() != "application/json":
                            raise ApiError(415, "Content-Type must be application/json")
                        raw = self.rfile.read(length)
                        if len(raw) != length:
                            raise ApiError(400, "Incomplete request body")
                        try:
                            body = json.loads(raw)
                        except (ValueError, UnicodeDecodeError):
                            raise ApiError(400, "Invalid JSON")
                        profile, created = provisioner.enroll(body)
                        self.reply(201 if created else 200, profile)
                        return
                    if self.command == "GET":
                        self.authorized(admin=True)
                        self.reply(200, provisioner.list_peers())
                        return
                if self.command == "DELETE" and self.path.startswith("/v1/peers/") and "?" not in self.path:
                    self.authorized(admin=True)
                    provisioner.revoke(unquote(self.path[len("/v1/peers/"):], errors="strict"))
                    self.reply(200, {"revoked": True})
                    return
                raise ApiError(404, "Unknown API endpoint")
            except ApiError as error:
                self.reply(error.status, {"error": str(error)})
            except DriverError:
                self.reply(503, {"error": "WireGuard is unavailable; retry with the same client key"})
            except (TimeoutError, ConnectionError):
                self.close_connection = True
            except Exception:
                LOG.error("Provisioning operation failed")
                self.reply(500, {"error": "Provisioning operation failed"})

        do_GET = dispatch
        do_POST = dispatch
        do_DELETE = dispatch
    return Handler


class ApiServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True
    request_queue_size = 32

    def handle_error(self, _request, _client_address):
        LOG.error("HTTP connection failed")


def main():
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    os.umask(0o077)
    provisioner = None
    try:
        settings = Settings.from_env()
        provisioner = Provisioner(settings)
        with ApiServer((settings.bind_host, settings.bind_port), handler_for(provisioner)) as server:
            LOG.info("Provisioning API ready")
            server.serve_forever()
    except KeyboardInterrupt:
        pass
    except (ValueError, OSError, sqlite3.Error, DriverError, ApiError) as error:
        # Configuration exceptions only contain field names, never raw credentials/output.
        LOG.error("Provisioning API could not start (%s)", type(error).__name__)
        return 1
    finally:
        if provisioner is not None:
            provisioner.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
